"""Generate the MITRE ATT&CK coverage report and an ATT&CK Navigator layer from the rules.

Usage:
    python tools/build_coverage.py          # (re)write docs/COVERAGE.md and docs/attack-navigator-layer.json
    python tools/build_coverage.py --check  # exit 1 if the committed files are out of date (used in CI)
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "rules"
DOCS = ROOT / "docs"
NAMES = yaml.safe_load((ROOT / "tools" / "attack_techniques.yml").read_text(encoding="utf-8"))
TECHNIQUE_TAG = re.compile(r"^attack\.(t\d{4}(?:\.\d{3})?)$")
LEVEL_SCORE = {"informational": 1, "low": 1, "medium": 2, "high": 3, "critical": 4}


def load_rules() -> list[tuple[Path, dict]]:
    return [
        (p, yaml.safe_load(p.read_text(encoding="utf-8")))
        for p in sorted(RULES.rglob("*.yml"))
    ]


def technique_url(tid: str) -> str:
    return "https://attack.mitre.org/techniques/" + tid.replace(".", "/") + "/"


def build() -> tuple[str, str]:
    rules = load_rules()
    by_technique: dict[str, list[tuple[Path, dict]]] = defaultdict(list)
    tactics_of: dict[str, set[str]] = defaultdict(set)

    for path, rule in rules:
        tags = rule.get("tags", [])
        tactics = [t.split(".", 1)[1] for t in tags if t.split(".", 1)[1] in NAMES["tactics"]]
        for tag in tags:
            m = TECHNIQUE_TAG.match(tag)
            if m:
                tid = m.group(1).upper()
                by_technique[tid].append((path, rule))
                tactics_of[tid].update(tactics)

    # ---- Markdown report ----
    lines = [
        "# MITRE ATT&CK coverage",
        "",
        "> Generated by `tools/build_coverage.py` — do not edit by hand.",
        "",
        f"**{len(rules)} rules** covering **{len(by_technique)} techniques** "
        f"across **{len({t for s in tactics_of.values() for t in s})} tactics** (ATT&CK v19).",
        "",
        "| Technique | Name | Tactic(s) | Rule(s) | Max level |",
        "|---|---|---|---|---|",
    ]
    for tid in sorted(by_technique):
        entries = by_technique[tid]
        rule_links = "<br>".join(
            f"[{r['title']}](../{p.relative_to(ROOT).as_posix()})" for p, r in entries
        )
        tactic_names = ", ".join(sorted(NAMES["tactics"][t] for t in tactics_of[tid]))
        max_level = max((r["level"] for _, r in entries), key=lambda lv: LEVEL_SCORE[lv])
        lines.append(
            f"| [{tid}]({technique_url(tid)}) | {NAMES['techniques'][tid]} | "
            f"{tactic_names} | {rule_links} | {max_level} |"
        )
    lines += [
        "",
        "Load [`attack-navigator-layer.json`](attack-navigator-layer.json) in the "
        "[ATT&CK Navigator](https://mitre-attack.github.io/attack-navigator/) to see this coverage on the matrix.",
        "",
    ]
    markdown = "\n".join(lines)

    # ---- ATT&CK Navigator layer ----
    layer = {
        "name": "detection-rules-lab coverage",
        "versions": {"layer": "4.5", "navigator": "5.1.0"},
        "domain": "enterprise-attack",
        "description": "Techniques covered by the Sigma rules in this repository.",
        "techniques": [
            {
                "techniqueID": tid,
                "score": max(LEVEL_SCORE[r["level"]] for _, r in by_technique[tid]),
                "comment": "; ".join(r["title"] for _, r in by_technique[tid]),
                "enabled": True,
                "showSubtechniques": "." in tid,
            }
            for tid in sorted(by_technique)
        ],
        "gradient": {"colors": ["#c6dbef", "#2171b5", "#08306b"], "minValue": 1, "maxValue": 4},
        "legendItems": [
            {"label": "medium", "color": "#6baed6"},
            {"label": "high", "color": "#2171b5"},
        ],
        "showTacticRowBackground": True,
        "selectTechniquesAcrossTactics": True,
    }
    navigator = json.dumps(layer, indent=2) + "\n"
    return markdown, navigator


def main() -> int:
    markdown, navigator = build()
    targets = {DOCS / "COVERAGE.md": markdown, DOCS / "attack-navigator-layer.json": navigator}
    if "--check" in sys.argv:
        stale = [p.name for p, c in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
        if stale:
            print(f"Out of date: {', '.join(stale)}. Run: python tools/build_coverage.py")
            return 1
        print("Coverage files are up to date.")
        return 0
    DOCS.mkdir(exist_ok=True)
    for path, content in targets.items():
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
